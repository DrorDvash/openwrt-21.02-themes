"""Regenerate tools/argon-template/*.htm from src/argon-2.3.1 (run from the repo root)."""
import re
A = "src/argon-2.3.1/luasrc/view/themes/argon/"
T = "tools/baselines/argon-template/"
hdr_note = "<%#\n Generated by tools/port-theme.py --baseline argon: @TITLE@ on Argon (luci-theme-@ID@).\n Template from luci-theme-argon 2.3.1 (jerrykuku, Apache-2.0); Argon's own uci settings,\n online wallpapers, polyfill and web manifest removed.\n-%>\n"

def fix_head(s):
    s, n = re.subn(r"\t-- Custom settings\n.*?\n\tend\n",
        "\t-- Fixed settings: this theme does not read Argon's own uci config\n"
        "\tlocal mode = '@MODE@'\n"
        "\tlocal dark_css = fs.readfile('/www' .. media .. '/css/dark.css') or ''\n"
        "\tlocal bar_color = '@THEMECOLOR@'\n", s, count=1, flags=re.S)
    assert n == 1, "settings block"
    s, n = re.subn(r"\s*<% if fs.access\('/etc/config/argon'\) then %>.*?<% end -%>", "", s, flags=re.S)
    assert n >= 1, "style blocks"
    s = re.sub(r'\t<link rel="apple-touch-icon" sizes="(60x60|72x72)"[^\n]*\n', "", s)
    s = re.sub(r'\t<link rel="icon" type="image/png" sizes="(96x96|16x16)"[^\n]*\n', "", s)
    s = re.sub(r'\t<link rel="manifest"[^\n]*\n', "", s)
    s = re.sub(r'\t<meta name="msapplication-TileImage"[^\n]*\n', "", s)
    s = s.replace('<link rel="shortcut icon" href="<%=media%>/favicon.ico">', '<link rel="shortcut icon" href="<%=media%>/favicon.png">')
    s = re.sub(r'\t<script src="<%=media%>/js/polyfill.min.js"></script>\n', "", s)
    s = s.replace('<%=media%>/css/cascade.css<%# ?v=PKG_VERSION %>', '<%=media%>/css/cascade.css?v=@VERSION@')
    s, k = re.subn(r"(\t</style>\n)", "\\1\t<link rel=\"stylesheet\" href=\"<%=media%>/css/theme.css?v=@VERSION@\">\n", s, count=1)
    assert k == 1, "theme.css link"
    # dark themes: let the 21.02 [data-darkmode] rules (zone badges, graphs, ...) apply
    s = s.replace('<html lang="<%=luci.i18n.context.lang%>">',
                  '<html lang="<%=luci.i18n.context.lang%>"<%= ifattr(mode == "dark", "data-darkmode", "true") %>>', 1)
    left = [w for w in ("polyfill", "manifest", "/etc/config/argon", "luci-static/argon") if w in s]
    assert not left, left
    return s

for n in ("header", "header_login"):
    open(T + n + ".htm", "w").write(hdr_note + fix_head(open(A + n + ".htm").read()))
for n in ("footer", "footer_login"):
    s = open(A + n + ".htm").read()
    s = s.replace('ArgonTheme <%# vPKG_VERSION %></a>', '@TITLE@ on ArgonTheme 2.3.1 (21.02 port)</a>')
    s = s.replace("L.require('menu-argon')", "L.require('menu-@ID@')")
    open(T + n + ".htm", "w").write(hdr_note + s)
open(T + "out_header_login.htm", "w").write(open(A + "out_header_login.htm").read())
s = open(A + "sysauth.htm").read()
s = s.replace("<%+themes/argon/out_header_login%>", "<%+themes/@ID@/out_header_login%>")
s = s.replace("<%+themes/argon/footer_login%>", "<%+themes/@ID@/footer_login%>")
s, n = re.subn(r'\t\tlocal bgUrl\t\t\t= media \.\. "/img/bg1\.jpg"', '\t\tlocal bgUrl\t\t\t= nil  -- no photo: the theme paints the login background', s); assert n == 1, "bgUrl"
s, n = re.subn(r"\t\tif fs.access\(\"/etc/config/argon\"\) then\n.*?\n\t\tend\n", "", s, count=1, flags=re.S); assert n == 1, "wallpaper"
s, n = re.subn(r'<div class="main-bg" id="main-bg" style="background-image:url\(<%=bgUrl%>\)"></div>',
               '<div class="main-bg" id="main-bg"<% if bgUrl then %> style="background-image:url(<%=bgUrl%>)"<% end %>></div>', s); assert n == 1, "main-bg"
s = s.replace('<%=media%>/img/argon.svg', '<%=media%>/logo.svg')
assert "online_wallpaper" not in s and "/etc/config/argon" not in s and "luci-static/argon" not in s
open(T + "sysauth.htm", "w").write(hdr_note + s)
print("templates ok")
